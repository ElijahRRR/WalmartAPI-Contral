def _hit(rule: Rule, fold: str) -> bool:
    if rule.catch_all:
        return True
    if rule.all_of and all(n in fold for n in rule.all_of):
        return True
    if any(n in fold for n in rule.needles):
        return True
    return bool(rule.pattern and rule.pattern.search(fold))


def _first_hit(fold: str, rules: Iterable[Rule]) -> Rule | None:
    for rule in rules:
        if _hit(rule, fold):
            return rule
    return None


