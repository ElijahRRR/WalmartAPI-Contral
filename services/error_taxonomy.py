class AtomResult(NamedTuple):
    """单原子归类结果。atom 保留**传进来的原文**(unknown 清单要全文,不要洗过的)。"""

    code: str
    policy_name: str | None
    policy_sub: str | None
    via_ai: bool
    rule_order: int
    unlisted_term: str | None       # 序 16 显式清单命中的那个词条
    atom: str


class Result(NamedTuple):
    """记录级归类结果(字段与方案 §3.5 逐字一致)。"""

    code: str
    name: str
    policy_name: str | None
    policy_sub: str | None
    via_ai: bool
    atom_codes: tuple[tuple[str, str | None], ...]
    unknown: tuple[str, ...]
    unlisted: tuple[tuple[str, int], ...]


class FeedResult(NamedTuple):
    """feed 报错归类结果。err_code/field 原样带回(operational 通道靠它们说话)。"""

    channel: str                    # content_ai / policy / async / operational
    code: str | None                # 16 码之一;async/operational 不强行进码表
    policy_name: str | None
    policy_sub: str | None
    via_ai: bool
    err_code: str | None
    field: str | None


def _classify(atom: str | None, rules: Iterable[Rule]) -> AtomResult:
    norm = normalize_atom(atom)
    rule = _first_hit(norm.fold, rules) or _RULE_UNKNOWN
    name, sub = extract_policy(atom)
    term = None
    if rule is _RULE_UNLISTED:
        term = next((n for n in rule.needles if n in norm.fold), None)
    return AtomResult(rule.code, name, sub, rule.via_ai, rule.order, term,
                      atom or "")


def classify_atom(atom: str | None) -> AtomResult:
    """输入:一条原子原文 → 输出:AtomResult(码 + 政策名 + AI 标记 + 命中序)。

    表序即优先级,首命中即码(方案 §3.3);序 0 命中即短路,正文不再进任何规则。
    """
    return _classify(atom, RULES)


def classify_reasons(atoms: Iterable[str] | None,
                     policy_names: Iterable[str] | None = None) -> Result:
    """输入:原子列表(+ 可选政策表集合)→ 输出:记录级 Result。

    主码 = 各原子码按 `ERROR_CATEGORY_SEVERITY` 取名次最小者(终局优先,
    非中性永远压过中性);记录级 policy_name/policy_sub 取**赢下主码那个原子**的
    (其余原子的政策名在 atom_codes 里逐条留着)。

    ⚠ `unknown` 引擎不吞:落 OTHER(未识别) 的原子原文全部带回,调用方必须告警。
    `policy_names` 只为 join 校验预留(见 policy_join),**不改判定、也不改
    policy_name 取值** —— 语料钉死抽出什么保留什么(`Auto and Motor Vehicles`
    不许被别名改写成 `Auto & Motor Vehicles`)。
    """
    results = [_classify(a, RULES) for a in (atoms or []) if (a or "").strip()]
    if not results:
        return Result("OTHER", resources.ERROR_CATEGORY_CODES["OTHER"],
                      None, None, False, (), (), ())
    win = min(results, key=lambda r: _SEVERITY_RANK[r.code])
    unlisted: dict[str, int] = {}
    for r in results:
        if r.unlisted_term:
            unlisted[r.unlisted_term] = unlisted.get(r.unlisted_term, 0) + 1
    return Result(
        code=win.code,
        name=resources.ERROR_CATEGORY_CODES[win.code],
        policy_name=win.policy_name,
        policy_sub=win.policy_sub,
        via_ai=any(r.via_ai for r in results),
        atom_codes=tuple((r.code, r.policy_name) for r in results),
        unknown=tuple(r.atom for r in results
                      if r.rule_order == _RULE_UNKNOWN.order),
        unlisted=tuple(sorted(unlisted.items())),
    )


def classify_feed_error(code: str | None, field: str | None,
                        description: str | None,
                        status: str | None) -> FeedResult:
    """输入:feed 报错四元组 → 输出:FeedResult(通道 + 码 + 政策名)。

    通道次序照方案 §3.6:
      1 code ∈ WALMART_ERR_CONTENT 或正文含 AI 尾句 → content_ai
        (**code 锚必须保留**:生产明细的 description 常被截断,AI 尾句可能不在截断内)
      2 field ∈ WALMART_ERR_FIELD_POLICY 且 status=='failed' → policy(正文过序 1-15)
      3 code ∈ WALMART_ERR_ASYNC_REVIEW → async(审查中,不是报错)
      4 其余 → operational,原样带回 (code, field);已结构化,不强行进 16 码表

    ⚠ `status=='failed'` 这道闸是硬的:生产契约里 SUCCESS 回执可以同时带
    ingestionErrors(带警告的成功),field 锚不许把它们判成政策拒。
    本步只被对照报告消费,**不接 listing_sheet.classify_receipt**。
    """
    fold = normalize_atom(description).fold
    if (code and code in resources.WALMART_ERR_CONTENT) or _AI_TAIL in fold:
        return FeedResult("content_ai", "CONTENT", None, None, True, code, field)
    if (field in resources.WALMART_ERR_FIELD_POLICY
            and (status or "").strip().casefold() == "failed"):
        atom = _classify(description, _POLICY_CHANNEL_RULES)
        return FeedResult("policy", atom.code, atom.policy_name, atom.policy_sub,
                          False, code, field)
    if code and code in resources.WALMART_ERR_ASYNC_REVIEW:
        return FeedResult("async", None, None, None, False, code, field)
    return FeedResult("operational", None, None, None, False, code, field)
