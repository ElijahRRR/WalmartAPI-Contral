_UNESCAPE_ROUNDS = 3            # &amp;amp; 双重转义:循环到不动点,≤3 次
_TAG_RE = re.compile(r"<[^>]{1,80}>")
# 链接标记 ||链文本@@@url||:保留链文本、丢 url。
# 分隔符写 @{2,} 而不是死的 @@@ —— 生产实见 `||Listing Quality Dashboard@@https…||`
# 只有两个 @(语料 reason#54),死写三个会把整条 url 留在正文里。
_LINK_RE = re.compile(r"\|\|([^|]*?)@{2,}[^|]*?\|\|")
# 残缺标记(无闭合 ||,语料 reason#10/#12/#28 的 `- )` 结尾那批):url 段只吃
# **一个非空白 token**,不吃到行尾 —— 吃到行尾会把标记后面的整句话一起吞掉
# (多原子记录里那可能正是 PROHIBITED_FINAL 那一句)。剥不净不报错(方案 §3.2.3)。
_LINK_BROKEN_RE = re.compile(r"\|\|([^|@]*)@{2,}\S*")


class Norm(NamedTuple):
    """规范化后的两个副本:text=原大小写(供政策名抽取),fold=casefold(供句式匹配)。"""

    text: str
    fold: str


def normalize_atom(text: str | None) -> Norm:
    """输入:一条原子原文 → 输出:Norm(原大小写副本, casefold 副本)。

    顺序照方案 §3.2:转义还原 → 剥 HTML 标签 → 剥链接标记 → 折叠空白。
    ⚠ 标签替成**空格**再折叠空白(方案原文写"→空"):生产实见
    `…Unpublished Items</p><p>&nbsp;page.</p>`,替空串会把 `Items` 与 `page`
    粘成一个词,而本引擎全靠子串匹配。折叠空白(第 4 步)会把多余空格收掉,
    两种写法在语料上输出一致。幂等:对已规范化的串再跑一次结果不变。
    """
    s = text or ""
    for _ in range(_UNESCAPE_ROUNDS):
        u = html.unescape(s)
        if u == s:
            break
        s = u
    s = _TAG_RE.sub(" ", s)
    s = _LINK_RE.sub(r"\1", s)
    s = _LINK_BROKEN_RE.sub(r"\1", s)
    s = s.replace("||", " ")            # 落单的裸标记:去掉,不粘词
    s = " ".join(s.split())             # \xa0(&nbsp;)也算空白,一并折叠
    return Norm(s, s.casefold())


def split_reasons(text: str | None) -> list[str]:
    """输入:库里的下架原因串 → 输出:原子列表(按 "; " 拆)。

    api/items.py 用 `"; ".join(reasons)` 落库,故拆分符是 "; "。
    ⚠ **整行含 AI 尾句时不拆**(方案 §3.1):那段文案自身带分号。
    拆分安全性已生产实证:最短原子 36 字符是完整句。
    """
    raw = (text or "").strip()
    if not raw:
        return []
    if _AI_TAIL in normalize_atom(raw).fold:
        return [raw]
    return [p.strip() for p in raw.split("; ") if p.strip()]


